BEGIN;
ALTER TABLE users ALTER COLUMN email DROP NOT NULL;
ALTER TABLE users ALTER COLUMN password_hash DROP NOT NULL;
ALTER TABLE users ADD COLUMN IF NOT EXISTS phone VARCHAR(20) UNIQUE;
ALTER TABLE users ADD COLUMN IF NOT EXISTS phone_verified_at TIMESTAMPTZ;
ALTER TABLE users ADD COLUMN IF NOT EXISTS email_verified_at TIMESTAMPTZ;
CREATE TABLE IF NOT EXISTS auth_identities (
 provider VARCHAR(16) NOT NULL CHECK(provider IN ('qq','github','google')), subject VARCHAR(255) NOT NULL,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 PRIMARY KEY(provider,subject), UNIQUE(user_id,provider)
);
CREATE TABLE IF NOT EXISTS auth_oauth_states (
 state_hash CHAR(64) PRIMARY KEY, provider VARCHAR(16) NOT NULL, verifier TEXT NOT NULL, nonce TEXT NOT NULL,
 redirect_path TEXT NOT NULL, link_user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
 expires_at TIMESTAMPTZ NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS auth_app_requests (
 id UUID PRIMARY KEY, challenge VARCHAR(43) NOT NULL, user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
 approved_at TIMESTAMPTZ, expires_at TIMESTAMPTZ NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
COMMIT;
